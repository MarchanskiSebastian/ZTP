CREATE TABLE IF NOT EXISTS categories (
    id        SERIAL PRIMARY KEY,
    name      VARCHAR(100) NOT NULL UNIQUE,
    min_price NUMERIC(10, 2) NOT NULL CHECK (min_price >= 0),
    max_price NUMERIC(10, 2) NOT NULL,
    CHECK (min_price <= max_price)
);

CREATE TABLE IF NOT EXISTS forbidden_names (
    id     SERIAL PRIMARY KEY,
    phrase VARCHAR(50) NOT NULL UNIQUE
);

CREATE TABLE IF NOT EXISTS products (
    id          SERIAL PRIMARY KEY,
    name        VARCHAR(20) NOT NULL UNIQUE,
    price       NUMERIC(10, 2) NOT NULL CHECK (price >= 0),
    quantity    INTEGER NOT NULL DEFAULT 0 CHECK (quantity >= 0),
    category_id INTEGER NOT NULL REFERENCES categories(id)
);

-- product_id is intentionally NOT a foreign key: history must survive product deletion
CREATE TABLE IF NOT EXISTS product_history (
    id             INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    product_id     INTEGER NOT NULL,
    action         VARCHAR NOT NULL,
    previous_state JSONB NOT NULL,
    current_state  JSONB NOT NULL,
    changed_at     TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE INDEX IF NOT EXISTS idx_product_history_product_id ON product_history(product_id);

